// Embeds public/lof-logo.png in the server code (src/assets/lof-logo.ts) for invoices, receipts and payment e-mails.
// Run after replacing the logo:  node scripts/build-logo.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const png = readFileSync(new URL('public/lof-logo.png', root));
if (png.toString('ascii', 1, 4) !== 'PNG') throw new Error('public/lof-logo.png is not a PNG file');
const w = png.readUInt32BE(16), h = png.readUInt32BE(20);
writeFileSync(new URL('src/assets/lof-logo.ts', root),
  `// GENERATED by scripts/build-logo.mjs from public/lof-logo.png (${w} x ${h}) – invoices, receipts and payment e-mails.\n` +
  `export const LOF_LOGO_PNG_B64 =\n  '${png.toString('base64')}';\n` +
  `export const LOF_LOGO_SIZE = { w: ${w}, h: ${h} };\n`);
console.log(`src/assets/lof-logo.ts written (${w} x ${h}, ${png.length} bytes)`);
